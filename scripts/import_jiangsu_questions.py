seen = set()
deduped = []
for q in all_questions:
    if q["questionText"] in seen:
        continue
    seen.add(q["questionText"])
    deduped.append(q)

def main():
    print(f"原始 {len(all_questions)} 题,去重后 {len(deduped)} 题")
    with open(OUT_JSON, "w", encoding="utf-8") as f:
        json.dump(deduped, f, ensure_ascii=False, indent=2)
    print(f"已写入 {OUT_JSON}")

    c = sqlite3.connect(DB)
    cur = c.cursor()
    inserted = 0
    skipped = 0
    for q in deduped:
        existing = cur.execute(
            "SELECT id FROM Question WHERE platform='jiangsu' AND questionText=?",
            (q["questionText"],),
        ).fetchone()
        if existing:
            skipped += 1
            continue
        cur.execute(
            """INSERT INTO Question
            (platform, category, questionText, options, answer, questionType, hitCount, createdAt, updatedAt)
            VALUES (?, ?, ?, ?, ?, ?, 0, datetime('now'), datetime('now'))""",
            (
                q["platform"],
                q["category"],
                q["questionText"],
                json.dumps(q["options"], ensure_ascii=False),
                q["answer"],
                q["questionType"],
            ),
        )
        inserted += 1
    c.commit()
    print(f"已写入 {inserted} 题,跳过已存在 {skipped} 题")

    total = cur.execute("SELECT COUNT(*) FROM Question WHERE platform='jiangsu'").fetchone()[0]
    by_cat = cur.execute(
        "SELECT COALESCE(category,'(无分类)'), COUNT(*) FROM Question WHERE platform='jiangsu' GROUP BY category ORDER BY 2 DESC"
    ).fetchall()
    by_type = cur.execute(
        "SELECT questionType, COUNT(*) FROM Question WHERE platform='jiangsu' GROUP BY questionType"
    ).fetchall()
    print(f"\n=== 江苏题库现状 ===")
    print(f"  总数: {total}")
    print(f"  按题型: {by_type}")
    print(f"  按分类:")
    for cat, n in by_cat:
        print(f"    {cat}: {n}")
    c.close()

if __name__ == "__main__":
    main()
