def to_schema(text: str, options: list, ans: str, src_label: str) -> dict:
    qtype = "judge" if options == ["对", "错"] else (
        "multiple" if len(ans) > 1 and all(c in "ABCDEF" for c in ans) else "single"
    )
    return {
        "platform": "jiangsu",
        "category": classify(text),
        "questionText": text.rstrip("。.?"),
        "options": options,
        "answer": ans,
        "questionType": qtype,
        "hitCount": 0,
        "_src": src_label,
    }

